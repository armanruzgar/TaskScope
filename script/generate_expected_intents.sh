#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<EOF
usage: $0 [--check]
Writes Sources/TaskScope/Models/ExpectedAppIntents+Source.swift from
script/expected_intents.json, the one list of the App Intents types and App
Shortcut phrases that packaging and Settings > Health expect. Run it after
changing the JSON. --check changes nothing and fails while the Swift file is
out of date.
EOF
}
[[ $# -le 1 ]] || { usage >&2; exit 2; }
CHECK=0
case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  --check) CHECK=1 ;;
  "") ;;
  *) usage >&2; exit 2 ;;
esac

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE="$ROOT_DIR/script/expected_intents.json"
OUTPUT="$ROOT_DIR/Sources/TaskScope/Models/ExpectedAppIntents+Source.swift"

# plutil -convert reads JSON, unlike plutil -lint.
/usr/bin/plutil -convert json -o /dev/null "$SOURCE" || {
  echo "$SOURCE is not valid JSON." >&2
  exit 1
}
# The JSON becomes a raw string literal, which this sequence would end.
if /usr/bin/grep -Fq '"""#' "$SOURCE"; then
  echo "$SOURCE must not contain the sequence \"\"\"#." >&2
  exit 1
fi

render() {
  cat <<'HEADER'
// Generated by script/generate_expected_intents.sh from
// script/expected_intents.json. Do not edit this file: change the JSON, then
// run the script. ExpectedAppIntentsTests fails while the two differ.

extension ExpectedAppIntents {
    /// The contents of script/expected_intents.json, which the packaging
    /// scripts read too.
    static let sourceJSON = #"""
HEADER
  # A multiline literal omits the newline before its closing delimiter.
  /usr/bin/sed -e '$a\' "$SOURCE"
  cat <<'FOOTER'
"""#
}
FOOTER
}

DRAFT="$(mktemp "${TMPDIR:-/tmp}/taskscope-expected-intents.XXXXXX")"
trap 'rm -f "$DRAFT"' EXIT
render > "$DRAFT"

if cmp -s "$DRAFT" "$OUTPUT"; then
  exit 0
fi
if [[ "$CHECK" -eq 1 ]]; then
  echo "$OUTPUT is out of date. Run script/generate_expected_intents.sh." >&2
  exit 1
fi
mv "$DRAFT" "$OUTPUT"
chmod 644 "$OUTPUT"
echo "Updated $OUTPUT"
